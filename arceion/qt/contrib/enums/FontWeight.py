__all__ = ["FontWeight"]


class FontWeight:
    """Represents a collection of font weight constants.

    This class defines commonly used font weight values, represented as
    integers. These constants can be used to specify the weight of a font in
    various contexts such as styling text in applications, documents, or web
    design. Each value corresponds to a common weight classification, providing
    developers with a convenient and standardized way to define font weights.

    Attributes:
        Thin (int): Represents the font weight value for 'Thin' (100).
        ExtraLight (int): Represents the font weight value for 'ExtraLight' (200).
        Light (int): Represents the font weight value for 'Light' (300).
        Normal (int): Represents the font weight value for 'Normal' (400).
        Medium (int): Represents the font weight value for 'Medium' (500).
        SemiBold (int): Represents the font weight value for 'SemiBold' (600).
        Bold (int): Represents the font weight value for 'Bold' (700).
        ExtraBold (int): Represents the font weight value for 'ExtraBold' (800).
        Black (int): Represents the font weight value for 'Black' (900).
    """

    Thin = 100
    ExtraLight = 200
    Light = 300
    Normal = 400
    Medium = 500
    SemiBold = 600
    Bold = 700
    ExtraBold = 800
    Black = 900
